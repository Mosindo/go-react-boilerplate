package photos

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
)

// Storage persists binary renditions. LocalStorage is the default; an object
// store (S3, GCS) can implement the same interface for horizontal scaling.
type Storage interface {
	Put(key string, data []byte) error
	Get(key string) ([]byte, error)
	Delete(key string) error
}

var ErrStorageNotFound = errors.New("stored object not found")

var keyRe = regexp.MustCompile(`^[0-9a-f-]{36}(_thumb)?\.jpg$`)

type LocalStorage struct{ root string }

func NewLocalStorage(root string) (*LocalStorage, error) {
	if err := os.MkdirAll(root, 0o750); err != nil {
		return nil, fmt.Errorf("create upload dir: %w", err)
	}
	return &LocalStorage{root: root}, nil
}

// path only accepts keys generated by this package, which rules out traversal.
func (s *LocalStorage) path(key string) (string, error) {
	if !keyRe.MatchString(key) {
		return "", fmt.Errorf("invalid storage key")
	}
	return filepath.Join(s.root, key), nil
}

func (s *LocalStorage) Put(key string, data []byte) error {
	p, err := s.path(key)
	if err != nil {
		return err
	}
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, data, 0o640); err != nil {
		return err
	}
	return os.Rename(tmp, p)
}

func (s *LocalStorage) Get(key string) ([]byte, error) {
	p, err := s.path(key)
	if err != nil {
		return nil, err
	}
	b, err := os.ReadFile(p)
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrStorageNotFound
	}
	return b, err
}

func (s *LocalStorage) Delete(key string) error {
	p, err := s.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}
