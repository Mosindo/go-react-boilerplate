package media

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
)

var ErrInvalidKey = errors.New("invalid storage key")

var keyPattern = regexp.MustCompile(`^[a-f0-9]{32}\.jpg$`)

// Storage persists processed images. LocalStorage is the default implementation;
// an object-storage backend can satisfy the same interface.
type Storage interface {
	Save(data []byte) (key string, err error)
	Path(key string) (string, error)
	Delete(key string) error
}

type LocalStorage struct {
	dir string
}

func NewLocalStorage(dir string) (*LocalStorage, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(abs, 0o750); err != nil {
		return nil, fmt.Errorf("create upload dir: %w", err)
	}
	return &LocalStorage{dir: abs}, nil
}

// ValidKey reports whether key has the exact shape generated by Save, which rules out
// path traversal before any filesystem access.
func ValidKey(key string) bool { return keyPattern.MatchString(key) }

func (s *LocalStorage) Save(data []byte) (string, error) {
	buf := make([]byte, 16)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	key := hex.EncodeToString(buf) + ".jpg"
	path := filepath.Join(s.dir, key)
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o640)
	if err != nil {
		return "", err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		_ = os.Remove(path)
		return "", err
	}
	if err := f.Close(); err != nil {
		_ = os.Remove(path)
		return "", err
	}
	return key, nil
}

func (s *LocalStorage) Path(key string) (string, error) {
	if !ValidKey(key) {
		return "", ErrInvalidKey
	}
	return filepath.Join(s.dir, key), nil
}

func (s *LocalStorage) Delete(key string) error {
	path, err := s.Path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}
